export function getTranslation(lang: string = 'en', key: string, params?: Record<string, string | number>): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS['en'] || TRANSLATIONS['de'];
  let text = dict[key] || TRANSLATIONS['en'][key] || TRANSLATIONS['de'][key] || key;
  if (params) {
    Object.keys(params).forEach((p) => {
      text = text.replace(`{${p}}`, String(params[p]));
    });
  }
  return text;
}

